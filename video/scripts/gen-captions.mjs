// Converts src/data/pedro.srt → src/data/captions.ts
// Rules (REBUILD_PROMPT §4): subtitles are 1–2 lines, ≤38 chars/line (we wrap
// at 32 so the pill clears the actor circle), timed off the .srt ±0.2s.
// Cues longer than 2 lines are split into sequential chunks; each chunk's
// window is the cue window divided proportionally by character count.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const srt = readFileSync(join(here, '../src/data/pedro.srt'), 'utf8')

const MAX_CHARS = 28

function toSec(t) {
  const m = t.match(/(\d+):(\d+):(\d+),(\d+)/)
  return +m[1] * 3600 + +m[2] * 60 + +m[3] + +m[4] / 1000
}

const cues = []
for (const block of srt.split(/\n\s*\n/)) {
  const lines = block.trim().split('\n')
  if (lines.length < 3) continue
  const times = lines[1].match(/([\d:,]+)\s*-->\s*([\d:,]+)/)
  if (!times) continue
  let text = lines.slice(2).join(' ').replace(/\s+/g, ' ').trim()
  // normalise the stuttered dots in the "Down .... Down" cue
  text = text.replace(/\.{2,}/g, '…').replace(/…\s*…/g, '…').replace(/\s+…/g, '…').replace(/…(?=[A-Za-z])/g, '… ')
  if (!text || /^[….\s]+$/.test(text)) continue // silence cues (24/25)
  cues.push({ start: toSec(times[1]), end: toSec(times[2]), text })
}

function wrap(text) {
  const words = text.split(' ')
  const lines = []
  let cur = ''
  for (const w of words) {
    if (cur && (cur + ' ' + w).length > MAX_CHARS) { lines.push(cur); cur = w }
    else cur = cur ? cur + ' ' + w : w
  }
  if (cur) lines.push(cur)
  return lines
}

// Split a cue's words into n runs of roughly equal character count so no
// chunk ends up a one-word orphan, then wrap each run into ≤2 lines.
function chunkText(text) {
  const words = text.split(' ')
  for (let n = Math.max(1, Math.ceil(wrap(text).length / 2)); n <= words.length; n++) {
    const total = text.length
    const target = total / n
    const runs = []
    let run = []
    let used = 0
    for (let i = 0; i < words.length; i++) {
      run.push(words[i])
      const len = run.join(' ').length
      const remainingWords = words.length - i - 1
      const remainingRuns = n - runs.length - 1
      if (runs.length < n - 1 && len + used >= target * (runs.length + 1) && remainingWords >= remainingRuns) {
        runs.push(run.join(' '))
        used += len + 1
        run = []
      }
    }
    if (run.length) runs.push(run.join(' '))
    const wrapped = runs.map(wrap)
    if (wrapped.every((w) => w.length <= 2)) return wrapped
  }
  return [wrap(text)]
}

const out = []
for (const cue of cues) {
  const chunks = chunkText(cue.text)
  const total = chunks.reduce((n, c) => n + c.join(' ').length, 0)
  let t = cue.start
  for (const chunk of chunks) {
    const span = ((cue.end - cue.start) * chunk.join(' ').length) / total
    out.push({ start: +t.toFixed(3), end: +(t + span).toFixed(3), lines: chunk })
    t += span
  }
}

const ts = `// AUTO-GENERATED by scripts/gen-captions.mjs from pedro.srt — do not edit.
export interface Caption { start: number; end: number; lines: string[] }
export const CAPTIONS: Caption[] = ${JSON.stringify(out, null, 2)}
`
writeFileSync(join(here, '../src/data/captions.ts'), ts)
const bad = out.filter((c) => c.lines.some((l) => l.length > 38) || c.lines.length > 2)
console.log(`captions: ${out.length} chunks from ${cues.length} cues; violations: ${bad.length}`)
for (const c of out) console.log(c.start.toFixed(1).padStart(6), '→', c.end.toFixed(1).padEnd(6), JSON.stringify(c.lines))
